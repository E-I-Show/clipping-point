const run = (k, phaseTitle, prompt) =>
  agent(head(k) + prompt, { label: 'spike:' + k, phase: phaseTitle, schema: SCHEMA }).catch(() => null)

const cfg = args || {}
const keys = cfg.keys || []
const promises = {}
for (const k of keys) promises[k] = run(k, 'Spikes', P[k] + (ADD[k] ? '\n\n' + ADD[k] : ''))

let assistP = null
if (cfg.assist) {
  assistP = Promise.all([promises.vehicle || Promise.resolve(null), promises.track || Promise.resolve(null)]).then(([veh, trk]) =>
    run('assist', 'Input assist', assistPrompt(veh, trk) + '\n\n' + ADD.assist))
}

const out = {}
for (const k of keys) {
  out[k] = await promises[k]
  log(k + ': ' + (out[k] ? '完了' : '未評価（結果なし）'))
}
if (assistP) {
  out.assist = await assistP
  log('assist: ' + (out.assist ? '完了' : '未評価（結果なし）'))
}

return out
