"""gen_bgm: what does it return, is it deterministic, how long are the parts; freeze 3 placeholder tunes as text."""
import json
import sys
from pathlib import Path

import pyxel

HERE = Path(__file__).resolve().parent
pyxel.init(64, 64, fps=1000, headless=True, quit_key=pyxel.KEY_NONE)
res = {}
a = pyxel.gen_bgm(0, 0, 3, 1234)
b = pyxel.gen_bgm(0, 0, 3, 1234)
c = pyxel.gen_bgm(0, 0, 3, 1235)
res["same_seed_same_output"] = a == b
res["other_seed_differs"] = a != c
res["example_preset0_instr3_seed1234"] = a


def lens(parts):
    out = []
    for p in parts:
        s = pyxel.Sound()
        s.mml(p)
        out.append(s.total_sec())
    return out


table = []
for preset in range(8):
    for instr in range(4):
        parts = pyxel.gen_bgm(preset, 0, instr, 7)
        table.append(dict(preset=preset, instr=instr, n_parts=len(parts), chars=[len(p) for p in parts], secs=lens(parts)))
res["table_seed7"] = table

# out-of-range arguments
for args in ((8, 0, 0, 1), (0, 6, 0, 1), (0, 0, 4, 1), (0, -5, 0, 1)):
    try:
        pyxel.gen_bgm(*args)
        res[f"gen_bgm{args}"] = "ok"
    except BaseException as e:
        res[f"gen_bgm{args}"] = f"{type(e).__name__}: {e}"

# freeze three placeholders: menu (preset 0, 4ch), replay (preset 4, melody+bass only), result (preset 2, 3ch)
tunes = {
    "menu": pyxel.gen_bgm(0, 0, 3, 101),
    "replay": pyxel.gen_bgm(4, 0, 2, 202),
    "result": pyxel.gen_bgm(2, 0, 0, 303),
}
res["frozen_secs"] = {k: lens(v) for k, v in tunes.items()}
out = ['"""Placeholder BGM frozen from pyxel.gen_bgm (Pyxel 3.0.1). Generated by exp/t05_bgm.py; do not edit by hand."""', "", "BGM = {"]
for k, parts in tunes.items():
    out.append(f"    {k!r}: [")
    for p in parts:
        out.append(f"        {p!r},")
    out.append("    ],")
out.append("}")
(HERE.parent / "proto" / "bgm_data.py").write_text("\n".join(out) + "\n")

# Music with MML sounds in the bank, rendered to WAV
for i, p in enumerate(tunes["menu"]):
    pyxel.sounds[i].mml(p)
pyxel.musics[0].set(*[[i] for i in range(len(tunes["menu"]))])
pyxel.musics[0].save(str(HERE / "out_t05_menu.wav"), 8.0)
res["music_seqs"] = [list(s) for s in pyxel.musics[0].seqs]
(HERE / "out_t05.json").write_text(json.dumps(res, indent=1))
print(json.dumps(res, indent=1)[:6000])
sys.exit(0)
